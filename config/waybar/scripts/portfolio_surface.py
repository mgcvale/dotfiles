#!/usr/bin/env python3
"""Export Waybar-only glass tints after pywal updates its palette."""

import json
from pathlib import Path


def surface_for(palette, palette_dir):
    for name, surface in (
        ("dark", "alpha(#777777, 0.14)"),
        ("light", "alpha(#ffffff, 0.12)"),
    ):
        reference = json.loads((palette_dir / f"{name}.json").read_text())
        if all(palette.get(key) == reference[key] for key in ("special", "colors")):
            return surface
    return "alpha(@background, 0.1)"


def main():
    home = Path.home()
    cache = home / ".cache/wal"
    palette = json.loads((cache / "colors.json").read_text())
    surface = surface_for(palette, home / ".config/wal/palettes")
    css = (
        "/* Generated by portfolio_surface.py; only affects the portfolio bar. */\n"
        f"@define-color portfolio_glass {surface};\n"
    )
    target = cache / "portfolio-surface.css"
    if not target.exists() or target.read_text() != css:
        target.write_text(css)


if __name__ == "__main__":
    main()
